@app.get("/")
def root():
    return RedirectResponse(url="/static/index.html")


@app.post("/students/signup")
def signup_student(payload: dict):
    """Register a new student account."""
    email = (payload.get("email") or "").strip().lower()
    password = (payload.get("password") or "").strip()
    name = (payload.get("name") or "").strip()

    if not email or "@" not in email:
        raise HTTPException(status_code=400, detail="A valid email is required")
    if len(password) < 6:
        raise HTTPException(status_code=400, detail="Password must be at least 6 characters")
    if not name:
        raise HTTPException(status_code=400, detail="Name is required")
    if email in students:
        raise HTTPException(status_code=409, detail="Student already exists")

    students[email] = {
        "name": name,
        "email": email,
        "password": password,
    }
    return {"message": f"Student {name} registered successfully", "student": {"name": name, "email": email}}


@app.post("/students/login")
def login_student(payload: dict):
    """Authenticate a student and return basic profile details."""
    email = (payload.get("email") or "").strip().lower()
    password = (payload.get("password") or "").strip()

    student = students.get(email)
    if not student or student["password"] != password:
        raise HTTPException(status_code=401, detail="Invalid email or password")

    return {"message": "Login successful", "student": {"name": student["name"], "email": student["email"]}}


@app.get("/activities")
def get_activities():
    return activities


@app.post("/activities/{activity_name}/signup")
def signup_for_activity(activity_name: str, email: str):
    """Sign up a student for an activity"""
    if activity_name not in activities:
        raise HTTPException(status_code=404, detail="Activity not found")

    if email.lower() not in students and email not in activities[activity_name]["participants"]:
        raise HTTPException(status_code=401, detail="Student must be registered before joining an activity")

    activity = activities[activity_name]

    if email in activity["participants"]:
        raise HTTPException(status_code=400, detail="Student is already signed up")

    if len(activity["participants"]) >= activity["max_participants"]:
        raise HTTPException(status_code=400, detail="Activity is full")

    activity["participants"].append(email)
    return {"message": f"Signed up {email} for {activity_name}"}


@app.delete("/activities/{activity_name}/unregister")
def unregister_from_activity(activity_name: str, email: str):
    """Unregister a student from an activity"""
    if activity_name not in activities:
        raise HTTPException(status_code=404, detail="Activity not found")

    activity = activities[activity_name]

    if email not in activity["participants"]:
        raise HTTPException(status_code=400, detail="Student is not signed up for this activity")

    activity["participants"].remove(email)
    return {"message": f"Unregistered {email} from {activity_name}"}
